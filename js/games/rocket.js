// Maths Rocket: every right answer moves the rocket up. Five right answers = blast off to the moon!
// 30 levels per child, each with its own theme (see LITTLE and BIG tables below).
import { shuffle, pick } from '../words.js';

const OBJ = ['🍎', '🍌', '⭐', '🐟', '🐞', '🍓', '⚽', '🌸', '🐥', '🧁', '🚗', '🦋'];
const OBJ_NAMES = ['apples', 'bananas', 'stars', 'fish', 'ladybirds', 'strawberries', 'balls', 'flowers', 'chicks', 'cupcakes', 'cars', 'butterflies'];
const STEPS = 5;

// Dice-style dots so non-readers can match amounts instead of reading numerals.
function dotsHTML(n, small = false) {
  const cols = n <= 3 ? n : n <= 4 ? 2 : n <= 6 ? 3 : n <= 8 ? 4 : 5;
  const d = small ? 14 : n > 10 ? 16 : 22;
  return `<div style="display:grid;grid-template-columns:repeat(${cols},${d}px);gap:${small ? 3 : 5}px;justify-content:center">${`<span style="width:${d}px;height:${d}px;border-radius:50%;background:#2B2140"></span>`.repeat(n)}</div>`;
}

/* ---------- Level tables ----------
   Each entry: [kind, options]. Kinds are generated by makeQuestion() below. */
const LITTLE = [
  ['count', { max: 3 }], ['count', { max: 4 }], ['count', { max: 5 }], ['more', { max: 5 }], ['count', { min: 2, max: 6 }],
  ['fewer', { max: 5 }], ['count', { min: 2, max: 7 }], ['count', { max: 5, numerals: true }], ['add', { max: 4 }], ['moreFewer', { max: 7 }],
  ['count', { min: 3, max: 8 }], ['oneMore', { max: 6 }], ['add', { max: 5 }], ['count', { min: 4, max: 9, numerals: true }], ['takeAway', { max: 5 }],
  ['count', { min: 5, max: 10 }], ['add', { max: 6 }], ['oneLess', { max: 7 }], ['moreFewer', { max: 10 }], ['takeAway', { max: 6 }],
  ['add', { max: 8 }], ['count', { min: 6, max: 10, numerals: true }], ['oneMoreLess', { max: 9 }], ['add', { max: 10 }], ['takeAway', { max: 8 }],
  ['count', { min: 8, max: 15, numerals: true }], ['add', { max: 10, numerals: true }], ['takeAway', { max: 10 }], ['addSub', { max: 10, numerals: true }], ['count', { min: 10, max: 20, numerals: true }],
];
const LITTLE_THEME = {
  count: 'Counting', more: 'Which has more?', fewer: 'Which has fewer?', moreFewer: 'More or fewer', add: 'Adding',
  takeAway: 'Taking away', oneMore: 'One more', oneLess: 'One less', oneMoreLess: 'One more, one less', addSub: 'Adding and taking away',
};
const BIG = [
  ['add', { max: 5, pics: true }], ['add', { max: 10, pics: true }], ['sub', { max: 5, pics: true }], ['sub', { max: 10, pics: true }], ['compare', { max: 20 }],
  ['add', { max: 10 }], ['sub', { max: 10 }], ['doubles', { max: 5 }], ['bonds', { to: 10 }], ['add', { max: 20 }],
  ['sub', { max: 20 }], ['addSub', { max: 20 }], ['missingAdd', { max: 20 }], ['doubles', { max: 10 }], ['halves', { max: 20 }],
  ['tens', {}], ['times', { t: [2] }], ['times', { t: [5] }], ['times', { t: [10] }], ['times', { t: [2, 5, 10] }],
  ['add2', { max: 50 }], ['sub2', { max: 50 }], ['bonds', { to: 20 }], ['missingSub', { max: 20 }], ['addTen', {}],
  ['three', { max: 9 }], ['times', { t: [3] }], ['times', { t: [4] }], ['share', {}], ['mix', {}],
];
const BIG_THEME = {
  add: 'Adding', sub: 'Taking away', compare: 'Bigger numbers', doubles: 'Doubles', bonds: 'Number bonds', addSub: 'Adding and taking away',
  missingAdd: 'Missing numbers', missingSub: 'Missing numbers', halves: 'Halves', tens: 'Counting in tens', times: 'Times tables',
  add2: 'Bigger adding', sub2: 'Bigger taking away', addTen: 'Adding ten', three: 'Three numbers', share: 'Sharing', mix: 'Everything mix',
};

export default function start(ctx) {
  const { stage, mode } = ctx;
  const little = mode === 'little';
  const table = little ? LITTLE : BIG;
  const [kind0, opt0] = table[Math.min(ctx.level, table.length) - 1];
  let step = 0, mistakes = 0, missesHere = 0, busy = false;
  ctx.dots(STEPS);
  ctx.hideMascot();

  stage.innerHTML = `
    <div style="display:flex;width:100%;flex:1;min-height:0;gap:14px;color:#fff">
      <div class="track" style="position:relative;width:clamp(90px,16vw,150px);flex:none;border-radius:30px;background:rgba(255,255,255,.08);overflow:visible">
        <div style="position:absolute;top:6px;left:50%;transform:translateX(-50%);font-size:clamp(46px,8vw,70px)">🌕</div>
        ${Array.from({ length: STEPS }, (_, i) => `<div style="position:absolute;left:50%;transform:translateX(-50%);bottom:${8 + (i + 1) * 15}%;width:40%;height:6px;border-radius:3px;background:rgba(255,255,255,.25)"></div>`).join('')}
        <div class="rocket" style="position:absolute;left:50%;bottom:2%;transform:translateX(-50%);font-size:clamp(56px,10vw,90px);transition:bottom .8s cubic-bezier(.3,1.4,.5,1)"><span style="display:inline-block;transform:rotate(-45deg)">🚀</span></div>
      </div>
      <div style="flex:1;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:14px;min-width:0">
        <div class="theme" style="font-size:clamp(16px,2.4vw,22px);color:#FFD23F;opacity:.9"></div>
        <div class="q prompt" style="color:#fff;font-size:clamp(36px,7vw,76px);margin:0"></div>
        <div class="objs" style="display:flex;flex-wrap:wrap;gap:6px;justify-content:center;align-items:center;max-width:680px;font-size:clamp(32px,5.5vw,56px);min-height:1.2em"></div>
        <div class="answers" style="display:flex;gap:clamp(12px,3vw,28px);flex-wrap:wrap;justify-content:center"></div>
      </div>
    </div>`;
  const rocket = stage.querySelector('.rocket');
  const qEl = stage.querySelector('.q');
  const objs = stage.querySelector('.objs');
  const answers = stage.querySelector('.answers');
  stage.querySelector('.theme').textContent = (little ? LITTLE_THEME : BIG_THEME)[kind0] || '';
  const rnd = (a, b) => a + ((Math.random() * (b - a + 1)) | 0);
  let lastKey = '';

  function obj() { const i = (Math.random() * OBJ.length) | 0; return [OBJ[i], OBJ_NAMES[i]]; }

  function group(o, n, cross = 0) {
    return `<span class="grp" style="display:inline-flex;flex-wrap:wrap;gap:4px;justify-content:center;max-width:${n > 5 ? '5.6em' : 'none'}">${Array.from({ length: n }, (_, i) => `<span style="${i >= n - cross ? 'opacity:.3;text-decoration:line-through;filter:grayscale(1)' : ''}">${o}</span>`).join('')}</span>`;
  }

  function makeQuestion(kind = kind0, opt = opt0) {
    const max = opt.max || 10;
    switch (kind) {
      /* ----- little ----- */
      case 'count': {
        const n = rnd(opt.min || 1, max); const [o, name] = obj();
        return { text: '❓', speak: `How many ${name}? Tap them to count, then find the answer!`, answer: n, visual: [{ o, n }], range: [1, max], say: `${n} ${name}!`, dots: !opt.numerals, numerals: opt.numerals };
      }
      case 'more': case 'fewer': case 'moreFewer': {
        const k = kind === 'moreFewer' ? pick(['more', 'fewer']) : kind;
        let a = rnd(1, max), b = rnd(1, max); while (a === b) b = rnd(1, max);
        const [o, name] = obj();
        const ans = k === 'more' ? (a > b ? 0 : 1) : (a < b ? 0 : 1);
        return { text: '', speak: `Which side has ${k} ${name}?`, answer: ans, choices: [group(o, a), group(o, b)], say: `That side has ${k}!` };
      }
      case 'add': {
        const a = rnd(1, max - 1), b = rnd(1, Math.max(1, max - a)); const [o, name] = obj();
        return { text: little ? '' : `${a} + ${b} = ?`, speak: little ? `${a} ${name}, and ${b} more. How many altogether?` : `What is ${a} plus ${b}?`, answer: a + b,
          visual: [{ o, n: a }, { plus: true }, { o, n: b }], range: [1, max], say: `${a} and ${b} makes ${a + b}!`, dots: little && !opt.numerals, numerals: opt.numerals };
      }
      case 'takeAway': {
        const a = rnd(2, max), b = rnd(1, a - 1); const [o, name] = obj();
        return { text: '', speak: `There were ${a} ${name}. ${b} went away. How many are left?`, answer: a - b, visual: [{ o, n: a, cross: b }], range: [0, max], say: `${a - b} left!`, dots: true };
      }
      case 'oneMore': case 'oneLess': case 'oneMoreLess': {
        const k = kind === 'oneMoreLess' ? pick(['oneMore', 'oneLess']) : kind;
        const n = k === 'oneMore' ? rnd(1, max - 1) : rnd(2, max); const [o, name] = obj();
        const ans = k === 'oneMore' ? n + 1 : n - 1;
        return { text: k === 'oneMore' ? '+1' : '−1', speak: `Here are ${n} ${name}. What is one ${k === 'oneMore' ? 'more' : 'less'}?`, answer: ans, visual: [{ o, n }], range: [0, max], say: `One ${k === 'oneMore' ? 'more' : 'less'} than ${n} is ${ans}!`, dots: true };
      }
      case 'addSub': return makeQuestion(Math.random() < .5 ? 'add' : 'takeAway', opt);
      /* ----- big ----- */
      case 'sub': {
        const a = rnd(2, max), b = rnd(1, a - 1); const [o] = obj();
        return { text: `${a} − ${b} = ?`, speak: `What is ${a} take away ${b}?`, answer: a - b, visual: opt.pics ? [{ o, n: a, cross: b }] : null, range: [0, max], say: `${a} take away ${b} is ${a - b}!` };
      }
      case 'compare': {
        let a = rnd(1, max), b = rnd(1, max); while (a === b) b = rnd(1, max);
        return { text: 'Which is bigger?', speak: `Which number is bigger, ${a} or ${b}?`, answer: Math.max(a, b), opts: [a, b], say: `${Math.max(a, b)} is bigger!` };
      }
      case 'doubles': {
        const a = rnd(1, max);
        return { text: `${a} + ${a} = ?`, speak: `What is double ${a}?`, answer: 2 * a, range: [0, 2 * max], say: `Double ${a} is ${2 * a}!` };
      }
      case 'bonds': {
        const a = rnd(0, opt.to);
        return { text: `${a} + ? = ${opt.to}`, speak: `${a} plus what makes ${opt.to}?`, answer: opt.to - a, range: [0, opt.to], say: `${a} and ${opt.to - a} make ${opt.to}!` };
      }
      case 'addSub': return makeQuestion(Math.random() < .5 ? 'add' : 'sub', opt);
      case 'missingAdd': {
        const a = rnd(1, 9), c = rnd(a + 1, max);
        return { text: `${a} + ? = ${c}`, speak: `${a} plus what makes ${c}?`, answer: c - a, range: [0, max], say: `${a} plus ${c - a} makes ${c}!` };
      }
      case 'missingSub': {
        const b = rnd(1, 9), c = rnd(1, max - b);
        return { text: `? − ${b} = ${c}`, speak: `What number, take away ${b}, leaves ${c}?`, answer: b + c, range: [0, max], say: `${b + c} take away ${b} is ${c}!` };
      }
      case 'halves': {
        const a = 2 * rnd(1, max / 2);
        return { text: `½ of ${a} = ?`, speak: `What is half of ${a}?`, answer: a / 2, range: [0, max / 2], say: `Half of ${a} is ${a / 2}!` };
      }
      case 'tens': {
        const a = 10 * rnd(1, 8), b = 10 * rnd(1, (100 - a) / 10);
        return { text: `${a} + ${b} = ?`, speak: `What is ${a} plus ${b}?`, answer: a + b, range: [10, 100], step: 10, say: `${a} plus ${b} is ${a + b}!` };
      }
      case 'times': {
        const t = pick(opt.t), n = rnd(1, 10);
        return { text: `${n} × ${t} = ?`, speak: `What is ${n} times ${t}?`, answer: n * t, range: [0, 10 * t], step: t, say: `${n} times ${t} is ${n * t}!`, visual: t <= 5 && n <= 5 ? Array.from({ length: n }, () => ({ o: '⚪', n: t, small: true })) : null };
      }
      case 'add2': {
        const a = rnd(11, max - 9), b = rnd(2, 9);
        return { text: `${a} + ${b} = ?`, speak: `What is ${a} plus ${b}?`, answer: a + b, range: [0, max + 9], say: `${a} plus ${b} is ${a + b}!` };
      }
      case 'sub2': {
        const a = rnd(12, max), b = rnd(2, 9);
        return { text: `${a} − ${b} = ?`, speak: `What is ${a} take away ${b}?`, answer: a - b, range: [0, max], say: `${a} take away ${b} is ${a - b}!` };
      }
      case 'addTen': {
        const a = rnd(11, 79);
        return { text: `${a} + 10 = ?`, speak: `What is ${a} plus ten?`, answer: a + 10, range: [0, 100], step: 10, say: `${a} plus 10 is ${a + 10}!` };
      }
      case 'three': {
        const a = rnd(1, max), b = rnd(1, max), c = rnd(1, max);
        return { text: `${a} + ${b} + ${c} = ?`, speak: `What is ${a} plus ${b} plus ${c}?`, answer: a + b + c, range: [0, 30], say: `That makes ${a + b + c}!` };
      }
      case 'share': {
        const t = pick([2, 5, 10]), n = rnd(1, 10);
        return { text: `${n * t} ÷ ${t} = ?`, speak: `Share ${n * t} sweets between ${t} friends. How many each?`, answer: n, range: [0, 12], say: `${n} each!` };
      }
      case 'mix': {
        const k = pick(['add2', 'sub2', 'doubles', 'bonds', 'times', 'missingAdd', 'halves', 'share']);
        const o = { add2: { max: 50 }, sub2: { max: 50 }, doubles: { max: 10 }, bonds: { to: 20 }, times: { t: [2, 3, 4, 5, 10] }, missingAdd: { max: 20 }, halves: { max: 20 }, share: {} }[k];
        return makeQuestion(k, o);
      }
    }
    return makeQuestion('count', { max: 5 });
  }

  function makeQ() {
    let q, guard = 0;
    do { q = makeQuestion(); } while (q.speak === lastKey && guard++ < 10);
    lastKey = q.speak;
    return q;
  }

  function show() {
    busy = false; missesHere = 0;
    const q = makeQ();
    qEl.textContent = q.text;
    qEl.style.fontSize = q.text.length > 12 ? 'clamp(28px,5vw,52px)' : '';
    objs.innerHTML = (q.visual || []).map(v => v.plus
      ? `<span style="color:#FFD23F;margin:0 10px">+</span>`
      : v.small ? `<span style="display:inline-flex;gap:2px;padding:4px 6px;border-radius:10px;background:rgba(255,255,255,.12);font-size:.45em">${v.o.repeat(v.n)}</span>`
      : group(v.o, v.n, v.cross)).join('');
    // Tapping a picture counts it out loud.
    let counted = 0;
    objs.querySelectorAll('.grp > span').forEach(s => s.addEventListener('pointerdown', () => {
      if (s._c || s.style.opacity === '0.3') return; s._c = true; counted++; s.style.transform = 'scale(.8)'; ctx.say(String(counted)); ctx.sfx.tap();
    }));
    answers.innerHTML = '';
    let list;
    if (q.choices) list = q.choices.map((html, i) => ({ v: i, html }));
    else {
      const opts = new Set(q.opts || [q.answer]);
      const stepN = q.step || 1;
      let guard = 0;
      while (!q.opts && opts.size < 3 && guard++ < 100) {
        const d = q.answer + pick([-2, -1, 1, 2, 3]) * stepN;
        if (d >= Math.max(0, q.range[0]) && d <= q.range[1] + 2 * stepN) opts.add(d);
      }
      list = [...opts].map(v => ({ v }));
    }
    shuffle(list).forEach(({ v, html }) => {
      const b = document.createElement('button');
      b.dataset.v = v;
      const wide = html || q.choices;
      if (html) b.innerHTML = html;
      else if (q.dots && v <= 12) b.innerHTML = dotsHTML(v);
      else if (q.numerals && v <= 10) b.innerHTML = `<div style="display:flex;flex-direction:column;align-items:center;gap:2px"><span style="line-height:1">${v}</span>${dotsHTML(v, true)}</div>`;
      else b.textContent = v;
      const big = String(v).length >= 3;
      b.style.cssText = wide
        ? 'min-width:clamp(140px,22vw,230px);min-height:clamp(100px,15vw,150px);padding:10px;border-radius:28px;background:#FFD23F;color:#2B2140;font-size:clamp(30px,5vw,48px);box-shadow:0 7px 0 #D9A400;display:grid;place-items:center'
        : `width:clamp(90px,14vw,130px);height:clamp(90px,14vw,130px);border-radius:${q.dots || q.numerals ? '28px' : '50%'};background:#FFD23F;color:#2B2140;font-size:${big ? 'clamp(32px,5vw,48px)' : 'clamp(40px,6.5vw,60px)'};box-shadow:0 7px 0 #D9A400;display:grid;place-items:center`;
      b.onclick = () => answer(b, v, q);
      answers.appendChild(b);
    });
    ctx.instruct(q.speak);
  }

  function answer(b, v, q) {
    if (busy) return;
    if (v === q.answer) {
      busy = true;
      step++;
      ctx.progress(step);
      ctx.right(b);
      ctx.sfx.whoosh();
      rocket.style.bottom = `${2 + step * 15}%`;
      ctx.say(q.say);
      if (step >= STEPS) {
        ctx.later(() => {
          ctx.say('3, 2, 1, blast off!');
          ctx.sfx.whoosh();
          rocket.style.transition = 'bottom 1.4s ease-in';
          rocket.style.bottom = '120%';
        }, 1800);
        ctx.later(() => ctx.finish(little ? 3 : mistakes <= 1 ? 3 : mistakes <= 4 ? 2 : 1), 3600);
      } else ctx.later(show, 2600);
    } else {
      mistakes++; missesHere++;
      ctx.wrong(b, q.choices ? 'Look again!' : q.dots ? `That's ${v}. Let's count again!` : 'Try again!');
      b.style.opacity = '.35';
      if (missesHere >= 2) [...answers.children].find(x => +x.dataset.v === q.answer)?.classList.add('hint');
    }
  }

  show();
  return () => {};
}
